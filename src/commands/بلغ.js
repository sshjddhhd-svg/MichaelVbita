// الإبلاغ عبر FCA
// ═══════════════════════════════════════════════════════════════════════════════
async function tryReport(api, msg) {
  for (const fn of ["reportMessage", "report", "reportSpam", "markAsSpam"]) {
    if (typeof api[fn] === "function") {
      try {
        await new Promise((res, rej) => api[fn](msg.messageID, (e) => e ? rej(e) : res()));
        return true;
      } catch (_) {}
    }
  }
  return false;
}

