const DANGEROUS_URL_PATTERNS = [
  { p: /https?:\/\/[^\s]*(faceb00k|f4cebook|facebok|faecbook|fb-log|facebook\.com-)/i, c: "PHISHING"  },
  { p: /https?:\/\/[^\s]*(paypa1|paypall|paipal|paypal\.com\.)/i,                     c: "PHISHING"  },
  { p: /https?:\/\/[^\s]*(free.*porn|porn.*free|xxx\.)/i,                               c: "SEXUAL_CONTENT" },
  { p: /https?:\/\/[^\s]*(drug|meth|heroin|weed|cannabis)[^.]*\.(com|net|org|io)/i,    c: "DRUGS"     },
  { p: /https?:\/\/[^\s]*(gun|weapon|arms|pistol)[^.]*\.(com|net|org)\//i,             c: "WEAPONS"   },
  { p: /https?:\/\/[^\s]*(hack|crack|phish|steal|inject)[^.]*\.(com|net|org)/i,        c: "HACKING"   },
  { p: /https?:\/\/bit\.ly\/|tinyurl\.com\/|t\.co\/[^\s]+/,                            c: "SPAM"      },
];

function analyzeUrl(text) {
  const results = [];
  for (const item of DANGEROUS_URL_PATTERNS) {
    if (item.p.test(text)) {
      results.push({
        ruleId: item.c, category: CONTEXT_RULES.find(r => r.id === item.c)?.cat || item.c,
        severity: "HIGH", score: 8, confidence: 85,
        reportType: "رابط خطير / مشبوه",
        description: `يحتوي على رابط مصنّف ضمن: ${item.c}`,
      });
    }
  }
  return results;
}

