// LAYER 2 — كشف النفي (Negation Detection)
// يمنع الإيجابيات الكاذبة: "لا أريد القتل" ≠ "سأقتلك"
// ═══════════════════════════════════════════════════════════════════════════════
const NEGATION_WORDS = /\b(لا|لن|لم|ما|مو|مش|مو|ليس|لست|لسنا|لستم|غير|بدون|دون|نرفض|رفض|ضد|احذر|تحذير|تجنب|توقف|ابتعد|لايجوز|ممنوع|حرام|مكروه|منع|نهى)\b/;
function hasNegationContext(text, matchStart, matchEnd) {
  // نأخذ 30 حرف قبل النص
  const before = text.slice(Math.max(0, matchStart - 30), matchStart);
  return NEGATION_WORDS.test(before);
}

