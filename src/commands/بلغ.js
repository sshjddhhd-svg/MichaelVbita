// فحص الملف الشخصي الكامل للمستهدف
async function checkProfile(api, targetUID) {
  const findings = [];
  let profileData = {};

  try {
    const info = await new Promise((res, rej) =>
      api.getUserInfo([targetUID], (e, d) => e ? rej(e) : res(d || {})));
    profileData = info[targetUID] || {};
  } catch (e) {
    return { findings, profileData, error: e.message };
  }

  // فحص الاسم الكامل
  if (profileData.name) {
    const nameViolations = analyzeProfileText(profileData.name);
    if (nameViolations.length) {
      findings.push({ source: "الاسم", text: profileData.name, violations: nameViolations });
    }
  }

  // فحص الاسم المستعار
  if (profileData.alternateName) {
    const altViolations = analyzeProfileText(profileData.alternateName);
    if (altViolations.length) {
      findings.push({ source: "الاسم المستعار", text: profileData.alternateName, violations: altViolations });
    }
  }

  // فحص الموقع الجغرافي المعلن
  if (profileData.location?.city) {
    const locViolations = analyzeProfileText(profileData.location.city);
    if (locViolations.length) {
      findings.push({ source: "الموقع", text: profileData.location.city, violations: locViolations });
    }
  }

  // فحص مجال العمل
  if (profileData.work && Array.isArray(profileData.work)) {
    for (const w of profileData.work.slice(0, 5)) {
      const wText = [w.employer?.name, w.position?.name, w.description].filter(Boolean).join(" ");
      if (wText) {
        const wViolations = analyzeProfileText(wText);
        if (wViolations.length) {
          findings.push({ source: "معلومات العمل", text: wText, violations: wViolations });
        }
      }
    }
  }

  // فحص التعليم
  if (profileData.education && Array.isArray(profileData.education)) {
    for (const edu of profileData.education.slice(0, 3)) {
      const eduText = [edu.school?.name, edu.concentration?.map?.(c => c.name)?.join(" ")].filter(Boolean).join(" ");
      if (eduText) {
        const eduViolations = analyzeProfileText(eduText);
        if (eduViolations.length) {
          findings.push({ source: "التعليم", text: eduText, violations: eduViolations });
        }
      }
    }
  }

  return { findings, profileData, error: null };
}

