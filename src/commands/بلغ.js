const ICON = { CRITICAL: "🔴", HIGH: "🟠", MEDIUM: "🟡", LOW: "🟢" };
const ORD  = { CRITICAL: 0, HIGH: 1, MEDIUM: 2, LOW: 3 };
const CONF = c => c >= 90 ? "مؤكدة 🔒" : c >= 70 ? "عالية ⬆️" : c >= 50 ? "متوسطة ➡️" : "محتملة ⬇️";
const RISK = (crit, high) =>
  crit >= 3 ? "🔴 خطر شديد جداً" : crit >= 1 ? "🟠 خطر عالٍ" :
  high >= 2 ? "🟡 خطر متوسط"    : "🟢 منخفض";

