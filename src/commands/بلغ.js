// جلب رسائل المستخدم من المحادثة
// ══════════════════════════════════════════════════════════════════════════════
async function getUserMessages(api, threadID, targetUID, maxFetch = 300) {
  const msgs = []; const seen = new Set();
  let timestamp = null;
  for (let i = 0; i < 7; i++) {
    let batch;
    try {
      batch = await new Promise((res, rej) =>
        api.getThreadHistory(threadID, 50, timestamp, (e, d) => e ? rej(e) : res(d || []))
      );
    } catch { break; }
    if (!batch.length) break;
    for (const m of batch) {
      const sid = String(m.senderID || m.authorID || "");
      if (sid === targetUID && m.body?.trim().length >= 2 && !seen.has(m.messageID)) {
        seen.add(m.messageID);
        msgs.push({ body: m.body.trim(), messageID: m.messageID, timestamp: m.timestamp });
      }
    }
    const oldest = batch[0]?.timestamp;
    if (!oldest || oldest === timestamp) break;
    timestamp = oldest;
    if (msgs.length >= maxFetch) break;
    await sleep(randInt(150, 350));
  }
  return msgs;
}

