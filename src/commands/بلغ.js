// الأمر الرئيسي
// ═══════════════════════════════════════════════════════════════════════════════
module.exports = {
  config: {
    name: "بلغ", aliases: ["report", "balagh", "balaghna"],
    description: "فحص عميق شامل لرسائل شخص والإبلاغ عن كل مخالفة وفق قوانين فيسبوك",
    usage: "بلغ  (ردّ على رسالة الشخص المستهدف)",
    adminOnly: true, ownerOnly: false, category: "admin",
  },

  async run({ api, event, threadID }) {
    const reply = event.messageReply;
    if (!reply) return api.sendMessage("⚠️ ردّ على رسالة الشخص المستهدف ثم اكتب: ميكائيل بلغ", threadID);

    const targetUID = String(reply.senderID || "");
    const botUID    = String(api.getCurrentUserID());
    if (!targetUID)  return api.sendMessage("❌ تعذّر تحديد الهوية.", threadID);
    if (targetUID === botUID) return api.sendMessage("❌ لا أستطيع الإبلاغ عن نفسي.", threadID);
    if (global.isAdmin?.(targetUID)) return api.sendMessage("❌ لا يمكن الإبلاغ عن أدمن البوت.", threadID);

    let targetName = targetUID;
    try {
      const info = await new Promise((res, rej) =>
        api.getUserInfo([targetUID], (e, d) => e ? rej(e) : res(d || {})));
      targetName = info[targetUID]?.name || targetUID;
    } catch (_) {}

    await api.sendMessage(
      `🔎 جارٍ الفحص الشامل لرسائل ${targetName}…\n` +
      `⚙️ 6 طبقات تحليل | 20 فئة مخالفة | كشف التمويه | تحليل الروابط\n⏳ انتظر…`,
      threadID
    );

    let userMessages;
    try { userMessages = await getUserMessages(api, threadID, targetUID, 300); }
    catch (e) { return api.sendMessage(`❌ فشل جلب الرسائل: ${e?.message || e}`, threadID); }

    if (!userMessages.length)
      return api.sendMessage(`ℹ️ لا توجد رسائل لـ ${targetName} في هذه المحادثة.`, threadID);

    // ── تحليل كل رسالة ───────────────────────────────────────────────────────
    const violations = [];
    let reportedCount = 0;

    for (const msg of userMessages) {
      const found = analyzeMessage(msg.body);
      if (found.length) {
        const reported = await tryReport(api, msg);
        if (reported) reportedCount++;
        violations.push({ msg, viols: found, reported });
      }
      await sleep(10); // تخفيف الحمل
    }

    // ── التحليل السلوكي ───────────────────────────────────────────────────────
    const behaviorViols = detectBehavior(userMessages);

    // ── لا مخالفات ────────────────────────────────────────────────────────────
    if (!violations.length && !behaviorViols.length) {
      return api.sendMessage(
        `✅ الفحص اكتمل — لا مخالفات\n${"─".repeat(30)}\n` +
        `👤 ${targetName}\n📊 رسائل مفحوصة: ${userMessages.length}\n` +
        `🔍 6 طبقات تحليل | 20 فئة | 120+ مؤشر\n\n` +
        `✅ جميع الرسائل نظيفة تماماً ولا تخالف قوانين مجتمع فيسبوك.`,
        threadID
      );
    }

    // ── تجميع النتائج ─────────────────────────────────────────────────────────
    const byId = new Map();
    for (const v of violations) {
      for (const viol of v.viols) {
        const e = byId.get(viol.ruleId);
        if (!e) {
          byId.set(viol.ruleId, { ...viol, count: 1, samples: [v.msg.body], maxConf: viol.confidence });
        } else {
          e.count++;
          e.maxConf = Math.max(e.maxConf, viol.confidence);
          e.score   = Math.max(e.score, viol.score);
          if (e.samples.length < 3) e.samples.push(v.msg.body);
        }
      }
    }
    for (const bv of behaviorViols) {
      byId.set(bv.id, { ruleId: bv.id, category: bv.cat, severity: bv.sev, reportType: bv.rt,
        description: bv.desc, count: 1, samples: [], maxConf: bv.confidence || 80, score: bv.sc });
    }

    const sorted = [...byId.values()].sort((a, b) => (ORD[a.severity] ?? 9) - (ORD[b.severity] ?? 9));
    const totalViol   = violations.length;
    const critCount   = sorted.filter(c => c.severity === "CRITICAL").length;
    const highCount   = sorted.filter(c => c.severity === "HIGH").length;
    const riskLabel   = RISK(critCount, highCount);

    // ── التقرير الرئيسي ───────────────────────────────────────────────────────
    let report =
      `🚨 تقرير البلاغات الشامل\n${"═".repeat(34)}\n` +
      `👤 الهدف: ${targetName}\n` +
      `📊 رسائل مفحوصة: ${userMessages.length}\n` +
      `🚫 رسائل مخالفة: ${totalViol}\n` +
      `📂 فئات مكتشفة: ${byId.size}\n` +
      `⚠️ مستوى الخطر: ${riskLabel}\n` +
      (reportedCount > 0 ? `📤 بلاغات قُدّمت: ${reportedCount}\n` : "") +
      `${"─".repeat(34)}\n\n📋 تفاصيل الفئات:\n\n`;

    for (const cat of sorted) {
      report +=
        `${ICON[cat.severity] || "⚪"} ${cat.category}\n` +
        `   📌 البلاغ: ${cat.reportType}\n` +
        `   🔢 رسائل مخالفة: ${cat.count}\n` +
        `   🎯 ثقة التحليل: ${CONF(cat.maxConf)}\n` +
        `   📝 ${cat.description}\n`;
      if (cat.samples?.length) {
        const sample = cat.samples[0].slice(0, 70) + (cat.samples[0].length > 70 ? "…" : "");
        report += `   💬 "${sample}"\n`;
      }
      report += "\n";
    }

    report += `${"─".repeat(34)}\n`;
    report += reportedCount > 0
      ? `✅ تم تقديم ${reportedCount} بلاغ لفيسبوك.\n⏳ ستُراجَع خلال 24-48 ساعة.`
      : `💡 ابلغ يدوياً:\n${sorted.slice(0, 3).map(c => `  • ${c.reportType}`).join("\n")}`;

    await api.sendMessage(report, threadID);

    // ── رسالة المخالفات الحرجة بالتفصيل ─────────────────────────────────────
    const critMsgs = violations.filter(v => v.viols.some(x => x.severity === "CRITICAL"));
    if (critMsgs.length) {
      await sleep(1200);
      let cm = `🔴 مخالفات حرجة — تفصيل:\n${"═".repeat(28)}\n\n`;
      for (const v of critMsgs.slice(0, 5)) {
        const cats = [...new Set(v.viols.filter(x => x.severity === "CRITICAL").map(x => x.category))];
        const mx   = Math.max(...v.viols.map(x => x.confidence));
        cm += `⛔ ${cats.join(" | ")}\n`;
        cm += `   ثقة: ${CONF(mx)}\n`;
        cm += `   💬 "${v.msg.body.slice(0, 90)}${v.msg.body.length > 90 ? "…" : ""}"\n\n`;
      }
      cm += `${"─".repeat(28)}\n⚡ تستلزم إجراءً فورياً وبلاغاً عاجلاً لفيسبوك.`;
      await api.sendMessage(cm, threadID);
    }

    // ── ملخص نهائي ────────────────────────────────────────────────────────────
    await sleep(800);
    await api.sendMessage(
      `📊 الملخص النهائي\n${"─".repeat(26)}\n` +
      `👤 ${targetName}\n` +
      `⚠️ ${riskLabel}\n` +
      `🚫 ${totalViol} / ${userMessages.length} رسالة مخالفة\n` +
      `📂 ${byId.size} فئة مخالفة\n` +
      `🔴 حرجة: ${critCount} | 🟠 عالية: ${highCount}\n` +
      (reportedCount > 0 ? `📤 ${reportedCount} بلاغ قُدّم ✅` : `💡 أبلغ يدوياً من داخل الرسائل`),
      threadID
    );
  },
};
