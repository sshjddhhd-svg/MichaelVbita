// LAYER 1 — ULTRA TEXT NORMALIZER
// يُطبّع النص بكل أشكال التمويه الممكنة
// ═══════════════════════════════════════════════════════════════════════════════
function normalize(raw) {
  if (!raw || typeof raw !== "string") return "";
  let t = raw;

  // 1) إزالة كل أشكال التشكيل والزوائد
  t = t.replace(/[\u064B-\u065F\u0610-\u061A\u0670\u06D6-\u06DC\u06DF-\u06E4\u06E7\u06E8\u06EA-\u06ED]/g, "");

  // 2) توحيد الألف وأشكاله
  t = t.replace(/[أإآاٱٲٳٵ]/g, "ا");

  // 3) توحيد الهمزة والواو والياء
  t = t.replace(/[ؤٶ]/g, "و");
  t = t.replace(/[ئ]/g, "ي");
  t = t.replace(/[ء]/g, "ء");

  // 4) توحيد التاء المربوطة والهاء
  t = t.replace(/ة/g, "ه");

  // 5) توحيد الألف المقصورة والياء
  t = t.replace(/ى/g, "ي");

  // 6) حروف متشابهة في لهجات مختلفة
  t = t.replace(/[گڭ]/g, "ك");
  t = t.replace(/[ڤڥ]/g, "ف");
  t = t.replace(/[پ]/g, "ب");
  t = t.replace(/[چ]/g, "ج");
  t = t.replace(/[ژ]/g, "ز");

  // 7) كشف التمويه بأرقام عربية وعالمية (leet speak)
  t = t.replace(/١/g,"1").replace(/٢/g,"2").replace(/٣/g,"3").replace(/٤/g,"4")
       .replace(/٥/g,"5").replace(/٦/g,"6").replace(/٧/g,"7").replace(/٨/g,"8")
       .replace(/٩/g,"9").replace(/٠/g,"0");

  // 8) أرقام لاتينية تُستخدم بدل حروف عربية
  t = t.replace(/(?<![0-9])3(?![0-9])/g, "ع");
  t = t.replace(/(?<![0-9])5(?![0-9])/g, "خ");
  t = t.replace(/(?<![0-9])6(?![0-9])/g, "ط");
  t = t.replace(/(?<![0-9])7(?![0-9])/g, "ح");
  t = t.replace(/(?<![0-9])8(?![0-9])/g, "ق");
  t = t.replace(/(?<![0-9])9(?![0-9])/g, "ص");
  t = t.replace(/(?<![0-9])4(?![0-9])/g, "ع");
  t = t.replace(/(?<![0-9])2(?![0-9])/g, "ء");

  // 9) رموز لاتينية تُستخدم بدل حروف عربية
  t = t.replace(/@/g, "ا").replace(/\$/g, "س").replace(/!/g, "ا");

  // 10) أحرف لاتينية تُستبدَل بما يشبهها عربياً (لكتابة عربي بلاتيني)
  t = t
    .replace(/\bkh\b/gi, "خ").replace(/\bgh\b/gi, "غ").replace(/\bth\b/gi, "ث")
    .replace(/\bsh\b/gi, "ش").replace(/\bdh\b/gi, "ذ").replace(/\bkh/gi, "خ")
    .replace(/\btj\b/gi, "ش");

  // 11) الكتابة العربية بحروف لاتينية (عربيزي) - أشيع الكلمات الخطيرة
  t = t
    .replace(/\bwlad el\s*kalb\b/gi, "ولاد الكلب")
    .replace(/\bibn el\s*sharmouta\b/gi, "ابن الشرموطه")
    .replace(/\bkos\s*(om|ommak|omak)\b/gi, "ش.ت.م")
    .replace(/\bsharmou[t]a\b/gi, "شرموطه")
    .replace(/\beahrek\b|\bahrak\b/gi, "احرق")
    .replace(/\bnaik\b|\bnayk\b/gi, "نيك")
    .replace(/\bkahba\b|\bqahba\b/gi, "قحبه")
    .replace(/\b3ahir\b|\b3ahre\b/gi, "عاهر")
    .replace(/\bhmar\b/gi, "حمار")
    .replace(/\bkhinzir\b/gi, "خنزير")
    .replace(/\bkalb\b/gi, "كلب")
    .replace(/\b7mar\b/gi, "حمار")
    .replace(/\bintahar\b|\bintaher\b/gi, "انتحر");

  // 12) إزالة فراغات مدسوسة بين حروف الكلمة العربية
  t = t.replace(/([ا-ي])\s+([ا-ي])/g, "$1$2");
  t = t.replace(/([ا-ي])\s+([ا-ي])/g, "$1$2"); // مرتين لكلمات أطول

  // 13) حذف نقاط وفواصل وخطوط مدسوسة بين الحروف
  t = t.replace(/([ا-ي])[._\-*|\\\/~`^]([ا-ي])/g, "$1$2");

  // 14) تطبيع تكرار الحرف
  t = t.replace(/(.)\1{3,}/g, "$1$1");

  // 15) تحويل لأحرف صغيرة
  t = t.toLowerCase();

  return t;
}

