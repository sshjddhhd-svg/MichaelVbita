const NEGATION_WORDS = /\b(لا|لن|لم|ما|مو|مش|ليس|لست|لسنا|لستم|غير|بدون|دون|نرفض|رفض|ضد|احذر|تحذير|تجنب|توقف|ابتعد|لايجوز|ممنوع|حرام|مكروه|منع|نهى|مستحيل|ابعد)\b/;

function hasNegationContext(text, matchStart) {
  const before = text.slice(Math.max(0, matchStart - 35), matchStart);
  return NEGATION_WORDS.test(before);
}

