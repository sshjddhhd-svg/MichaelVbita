// المحرك الرئيسي — تحليل رسالة واحدة (6 طبقات)
// ═══════════════════════════════════════════════════════════════════════════════
function analyzeMessage(rawText) {
  if (!rawText || typeof rawText !== "string" || rawText.trim().length < 2) return [];

  const norm   = normalize(rawText);
  const scores = new Map(); // ruleId → { meta, score }

  // ── طبقة 2: قائمة الكلمات السوداء ───────────────────────────────────────
  for (const item of TOKEN_BLACKLIST) {
    const m = norm.match(item.t);
    if (m) {
      const e = scores.get(item.c) || { score: 0 };
      // فحص النفي — تخفيض الدرجة إذا وُجد نفي مجاور
      const idx = norm.indexOf(m[0]);
      const boost = hasNegationContext(norm, idx, idx + m[0].length) ? 0.3 : 1;
      e.score += item.s * boost;
      scores.set(item.c, e);
    }
  }

  // ── طبقة 3: قواعد السياق ────────────────────────────────────────────────
  for (const rule of CONTEXT_RULES) {
    for (const pat of rule.p) {
      const m = norm.match(pat);
      if (m) {
        const idx = norm.indexOf(m[0]);
        const negated = hasNegationContext(norm, idx, idx + m[0].length);
        const existing = scores.get(rule.id) || { score: 0, meta: rule };
        existing.meta = rule;
        existing.score += negated ? rule.sc * 0.2 : rule.sc;
        scores.set(rule.id, existing);
        break;
      }
    }
  }

  // ── طبقة 5: روابط خطيرة ──────────────────────────────────────────────────
  const urlViolations = analyzeUrl(rawText);
  for (const uv of urlViolations) {
    const e = scores.get(uv.ruleId) || { score: 0, meta: CONTEXT_RULES.find(r => r.id === uv.ruleId) };
    e.score += 8;
    scores.set(uv.ruleId, e);
  }

  // ── تحويل النقاط إلى نتائج مع عتبة الثقة ────────────────────────────────
  const META = Object.fromEntries(CONTEXT_RULES.map(r => [r.id, r]));
  const SEV_SC = { CRITICAL: 10, HIGH: 7, MEDIUM: 5, LOW: 3 };
  const results = [];

  for (const [id, entry] of scores.entries()) {
    const meta = entry.meta || META[id] || {};
    const sev  = meta.sev || "MEDIUM";
    const threshold = SEV_SC[sev] || 5;
    if (entry.score < threshold * 0.5) continue; // تجاهل النتائج الضعيفة جداً

    const confidence = Math.min(100, Math.round((entry.score / (threshold * 1.5)) * 100));
    if (confidence < 30) continue; // حد أدنى للثقة

    results.push({
      ruleId:      id,
      category:    meta.cat      || id,
      severity:    sev,
      reportType:  meta.rt       || id,
      description: meta.desc     || "",
      score:       Math.round(entry.score * 10) / 10,
      confidence:  Math.min(confidence, 99),
    });
  }

  return results.sort((a, b) => b.score - a.score);
}

